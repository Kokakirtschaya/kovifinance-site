#!/bin/sh
# Старт контейнера: сначала догоняем схему базы, потом поднимаем сайт.
# migrate deploy применяет только уже созданные миграции и никогда не трогает
# данные — в отличие от migrate dev, которую на проде запускать нельзя.
set -e

if [ -n "$DATABASE_URL" ]; then
  echo "→ Применяю миграции базы..."
  node /opt/prisma-cli/node_modules/prisma/build/index.js migrate deploy
  echo "→ База готова."
else
  # Сайт и форма заявок работают и без базы — она нужна только личному кабинету.
  echo "⚠ DATABASE_URL не задан: миграции пропущены, личный кабинет работать не будет."
fi

exec "$@"
